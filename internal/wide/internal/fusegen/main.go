// Command fusegen writes the fused programs of the package wide (D98).
//
// A fused program is a copy of a program of stages of the raster pipeline
// of okage. The stages keep the channels of 8 or 16 pixels in the memory of
// the pipeline, and each stage calls the next. A fused program runs the same
// arithmetic on each pixel, in the same order, and keeps its values in
// registers through the whole program. So it gives the same bytes as the
// stages (D16), and the test TestFusedPrograms of the root package makes
// sure of that on random inputs.
//
// Run it with "go generate ./internal/wide", which runs it in the folder of
// the package. It writes these files:
//
//	fused_programs.go     the names of the programs and the scalar code of each, in every build
//	fused_scalar.go       FusedRow in a build without the SIMD code
//	fused_simd_amd64.go   FusedRow and the SIMD code of each program, with archsimd on amd64
//
// Each generated file starts with the line
// "// Code generated by fusegen. DO NOT EDIT." Do not edit such a file. Edit
// the table of this program, and run fusegen again. The file fused.go of the
// package, with the type FusedCtx, is written by hand, and so are the
// helpers of the SIMD code in wide_simd_amd64.go.
//
// The scalar code works on one pixel at a time. The SIMD code works on 8
// pixels at a time with archsimd.Float32x8 and archsimd.Uint32x8, and the
// scalar code draws the pixels that are left. arm64 and wasm run the scalar
// code, because their SIMD code was not written or measured.
//
// # The language of the table
//
// The body of a program is a list of statements, one on each line. A
// statement is "name = op operands", or "op operands" for an op that gives
// no value. A name holds a float32 or a 16-bit integer, by its op, and a
// later statement can give the name a new value of the same kind. An
// operand is a name, or a literal such as #255 or #0.5. The ops are:
//
//	xs = seedx               the x of the pixel, as seed_shader gives it
//	ys = seedy               the y of the pixel, as seed_shader gives it
//	v = fparam Field[i]      a float32 field of FusedCtx
//	v = iparam Field[i]      a uint16 field of FusedCtx
//	v = madd a b c           float32(a*b) + c, as mad of the stages
//	v = fmul a b             float32(a * b)
//	v = fsub a b             a - b
//	v = clamp01 a            LaneMin(LaneMax(a, 0), 1), as normalize
//	v = tou16 a              TruncU16(a), as save_to_u16x16
//	v = imul a b             a * b, wrapped to 16 bits
//	v = iadd a b             a + b, wrapped to 16 bits
//	v = isub a b             a - b, wrapped to 16 bits
//	v = div255 a             (a + 255) >> 8, as div255 of lowp
//	r g b a = loadf          the pixel as floats, as load_8888 of highp
//	r g b a = loadi          the pixel as integers, as load_8888 of lowp
//	m = loadmask             the byte of the mask of the pixel, as mask_u8 reads it
//	skipzero m               skip the pixel when m is 0
//	storef r g b a           store the pixel as store_8888 of highp
//	storei r g b a           store the pixel as store_8888 of lowp
//
// The SIMD code holds a 16-bit integer in a lane of 32 bits. The low 16 bits
// of a lane are right after each add, subtract and multiply. fusegen tracks
// the largest value of each lane, and it clears the high 16 bits before a
// shift when they can be other than 0.
