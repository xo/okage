// scaleI scales the color by the name s, as scale_1_float and mask_u8 of
// lowp do.
func scaleI(s string) string {
	var b strings.Builder
	for _, c := range []string{"r", "g", "b", "a"} {
		fmt.Fprintf(&b, "%s = imul %s %s\n%s = div255 %s\n", c, c, s, c, c)
	}
	return b.String()
}

