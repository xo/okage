// The bounds of the fields of FusedCtx that iparam reads. The doc comment of
// FusedCtx gives them to the caller.
var paramBound = map[string]uint64{"RGBA": 0xff, "Coverage": 0xff}

// reserved holds the names of the generated code that a statement cannot
// use.
var reserved = map[string]bool{
	"c": true, "px": true, "mask": true, "x0": true, "y0": true, "start": true,
	"n": true, "i": true, "j": true, "p": true, "pxv": true, "iot": true, "iotaLo": true, "iotaHi": true,
}

// stmt is one parsed statement.
type stmt struct {
	outs []string
	op   string
	args []string
}

// parse parses the body of a program.
func parse(p program) []stmt {
	var out []stmt
	for line := range strings.SplitSeq(p.body, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		var s stmt
		lhs, rhs, ok := strings.Cut(line, "=")
		if ok {
			s.outs = strings.Fields(lhs)
		} else {
			rhs = line
		}
		f := strings.Fields(rhs)
		s.op, s.args = f[0], f[1:]
		for _, n := range s.outs {
			if reserved[n] {
				log.Fatalf("%s: the name %s is reserved", p.name, n)
			}
		}
		out = append(out, s)
	}
	return out
}

// uniform reports whether a statement gives the same value for each pixel
// of a row, so that the code computes it once before its loop.
func uniform(s stmt) bool {
	return s.op == opFparam || s.op == opIparam || s.op == opSeedy
}

// kinds gives the kind of each name of a program: 'f' for float32 and 'i'
// for a 16-bit integer.
func kinds(p program, ss []stmt) map[string]byte {
	k := map[string]byte{}
	set := func(n string, v byte) {
		if old, ok := k[n]; ok && old != v {
			log.Fatalf("%s: %s changes its kind", p.name, n)
		}
		k[n] = v
	}
	for _, s := range ss {
		var v byte
		switch s.op {
		case opSeedx, opSeedy, opFparam, opMadd, opFmul, opFsub, opClamp01, opLoadf:
			v = 'f'
		case opIparam, opImul, opIadd, opIsub, opDiv255, opTou16, opLoadi, opLoadmask:
			v = 'i'
		case opSkipzero, opStoref, opStorei:
			continue
		default:
			log.Fatalf("%s: unknown op %s", p.name, s.op)
		}
		for _, n := range s.outs {
			set(n, v)
		}
	}
	return k
}

// scalarOperand gives the Go form of an operand in the scalar code.
func scalarOperand(a string) string {
	if strings.HasPrefix(a, "#") {
		return a[1:]
	}
	return a
}

// scalarFunc gives the scalar code of a program: a function that draws the
// pixels from start to n of a row.
func scalarFunc(p program) string {
	ss := parse(p)
	kinds(p, ss)
	var pre, body bytes.Buffer
	// A name gets a new variable in the loop the first time that the loop
	// gives it a value, so that each pixel starts from the value before
	// the loop.
	declared := map[*bytes.Buffer]map[string]bool{&pre: {}, &body: {}}
	assign := func(w *bytes.Buffer, n, expr string) {
		if n == "_" {
			fmt.Fprintf(w, "_ = %s\n", expr)
			return
		}
		op := "="
		if !declared[w][n] {
			op = ":="
			declared[w][n] = true
		}
		fmt.Fprintf(w, "%s %s %s\n", n, op, expr)
	}
	usesMask, usesY, usesX := false, false, false
	for _, s := range ss {
		a := make([]string, len(s.args))
		for i, x := range s.args {
			a[i] = scalarOperand(x)
		}
		w := &body
		if uniform(s) {
			w = &pre
		}
		switch s.op {
		case opSeedx:
			usesX = true
			assign(w, s.outs[0], fmt.Sprintf("float32(x0+j-j%%%d) + (float32(j%%%d) + 0.5)", p.group, p.group))
		case opSeedy:
			usesY = true
			assign(w, s.outs[0], "float32(y0) + 0.5")
		case opFparam:
			assign(w, s.outs[0], "c."+a[0])
		case opIparam:
			assign(w, s.outs[0], "c."+a[0])
		case opMadd:
			assign(w, s.outs[0], fmt.Sprintf("float32(%s*%s) + %s", a[0], a[1], a[2]))
		case opFmul:
			assign(w, s.outs[0], fmt.Sprintf("float32(%s * %s)", a[0], a[1]))
		case opFsub:
			assign(w, s.outs[0], fmt.Sprintf("%s - %s", a[0], a[1]))
		case opClamp01:
			assign(w, s.outs[0], fmt.Sprintf("LaneMin(LaneMax(%s, 0), 1.0)", a[0]))
		case opTou16:
			assign(w, s.outs[0], fmt.Sprintf("TruncU16(%s)", a[0]))
		case opImul:
			assign(w, s.outs[0], fmt.Sprintf("%s * %s", a[0], a[1]))
		case opIadd:
			assign(w, s.outs[0], fmt.Sprintf("%s + %s", a[0], a[1]))
		case opIsub:
			assign(w, s.outs[0], fmt.Sprintf("%s - %s", a[0], a[1]))
		case opDiv255:
			assign(w, s.outs[0], fmt.Sprintf("(%s + 255) >> 8", a[0]))
		case opLoadf:
			for k, n := range s.outs {
				assign(w, n, fmt.Sprintf("float32(p[%d]) * fusedUnit", k))
			}
		case opLoadi:
			for k, n := range s.outs {
				assign(w, n, fmt.Sprintf("uint16(p[%d])", k))
			}
		case opLoadmask:
			usesMask = true
			assign(w, s.outs[0], "uint16(mask[j])")
		case opSkipzero:
			fmt.Fprintf(w, "if %s == 0 {\ncontinue\n}\n", a[0])
		case opStoref:
			for k, n := range a {
				fmt.Fprintf(w, "p[%d] = uint8(LaneRoundIntByte(float32(LaneMin(LaneMax(%s, 0), 1.0) * 255.0)))\n", k, n)
			}
		case opStorei:
			for k, n := range a {
				fmt.Fprintf(w, "p[%d] = uint8(%s)\n", k, n)
			}
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// fused%sScalar draws the pixels from start to n of a row with the\n", p.name)
	fmt.Fprintf(&b, "// program Fused%s, one pixel at a time.\n", p.name)
	fmt.Fprintf(&b, "func fused%sScalar(c *FusedCtx, px, mask []byte, x0, y0, start, n int) {\n", p.name)
	if !usesMask {
		b.WriteString("_ = mask\n")
	}
	if !usesX {
		b.WriteString("_ = x0\n")
	}
	if !usesY {
		b.WriteString("_ = y0\n")
	}
	b.Write(pre.Bytes())
	b.WriteString("for j := start; j < n; j++ {\np := (*[4]byte)(px[j*4:])\n")
	b.Write(body.Bytes())
	b.WriteString("}\n}\n\n")
	return b.String()
}

// simdFunc gives the SIMD code of a program on amd64: a function that draws
// the pixels of a row 8 at a time, and the pixels that are left with the
// scalar code.
func simdFunc(p program) string {
	ss := parse(p)
	kind := kinds(p, ss)
	var pre, body bytes.Buffer
	// A name gets a new variable in the loop the first time that the loop
	// gives it a value, so that each pixel starts from the value before
	// the loop.
	declared := map[*bytes.Buffer]map[string]bool{&pre: {}, &body: {}}
	bound := map[string]uint64{}
	consts := map[string]string{}
	var constOrder []string
	assign := func(w *bytes.Buffer, n, expr string) {
		if n == "_" {
			fmt.Fprintf(w, "_ = %s\n", expr)
			return
		}
		op := "="
		if !declared[w][n] {
			op = ":="
			declared[w][n] = true
		}
		fmt.Fprintf(w, "%s %s %s\n", n, op, expr)
	}
	// operand gives the vector of an operand of the kind k, and its bound.
	operand := func(a string, k byte) (string, uint64) {
		if !strings.HasPrefix(a, "#") {
			return a, bound[a]
		}
		lit := a[1:]
		name := "k" + string(k) + strings.NewReplacer(".", "p", "-", "m").Replace(lit)
		if _, ok := consts[name]; !ok {
			if k == 'f' {
				consts[name] = fmt.Sprintf("archsimd.BroadcastFloat32x8(%s)", lit)
			} else {
				consts[name] = fmt.Sprintf("archsimd.BroadcastUint32x8(%s)", lit)
			}
			constOrder = append(constOrder, name)
		}
		v, err := strconv.ParseUint(lit, 10, 64)
		if err != nil && k == 'i' {
			log.Fatalf("%s: the integer literal %s", p.name, lit)
		}
		return name, v
	}
	// reduce gives the vector of the name n with the high 16 bits of each
	// lane cleared, when they can be other than 0.
	reduce := func(n string, b uint64) (string, uint64) {
		if b <= 0xffff {
			return n, b
		}
		consts["k16"] = "archsimd.BroadcastUint32x8(0xffff)"
		return n + ".And(k16)", 0xffff
	}
	const huge = 1 << 32
	capB := func(b uint64) uint64 { return min(b, huge) }
	usesSeedX, usesPx, usesMask := false, false, false
	for _, s := range ss {
		w := &body
		if uniform(s) {
			w = &pre
		}
		var k byte = 'i'
		if len(s.outs) > 0 {
			k = kind[s.outs[0]]
		} else if len(s.args) > 0 && strings.HasPrefix(s.op, opStoref) {
			k = 'f'
		}
		a := make([]string, len(s.args))
		ab := make([]uint64, len(s.args))
		for i, x := range s.args {
			a[i], ab[i] = operand(x, k)
		}
		out := ""
		if len(s.outs) > 0 {
			out = s.outs[0]
		}
		switch s.op {
		case opSeedx:
			usesSeedX = true
			assign(w, out, fmt.Sprintf("archsimd.BroadcastFloat32x8(float32(x0 + i - i%%%d)).Add(iot)", p.group))
		case opSeedy:
			assign(w, out, "archsimd.BroadcastFloat32x8(float32(y0) + 0.5)")
		case opFparam:
			assign(w, out, fmt.Sprintf("archsimd.BroadcastFloat32x8(c.%s)", s.args[0]))
		case opIparam:
			field, _, _ := strings.Cut(s.args[0], "[")
			b, ok := paramBound[field]
			if !ok {
				log.Fatalf("%s: no bound for %s", p.name, field)
			}
			assign(w, out, fmt.Sprintf("archsimd.BroadcastUint32x8(uint32(c.%s))", s.args[0]))
			bound[out] = b
		case opMadd:
			assign(w, out, fmt.Sprintf("%s.Mul(%s).Add(%s)", a[0], a[1], a[2]))
		case opFmul:
			assign(w, out, fmt.Sprintf("%s.Mul(%s)", a[0], a[1]))
		case opFsub:
			assign(w, out, fmt.Sprintf("%s.Sub(%s)", a[0], a[1]))
		case opClamp01:
			k0, _ := operand("#0", 'f')
			k1, _ := operand("#1", 'f')
			assign(w, out, fmt.Sprintf("vMin8(vMax8(%s, %s), %s)", a[0], k0, k1))
		case opTou16:
			assign(w, out, fmt.Sprintf("vTruncU16x8(%s)", a[0]))
			bound[out] = 0xffff
		case opImul:
			assign(w, out, fmt.Sprintf("%s.Mul(%s)", a[0], a[1]))
			bound[out] = capB(ab[0] * ab[1])
		case opIadd:
			assign(w, out, fmt.Sprintf("%s.Add(%s)", a[0], a[1]))
			bound[out] = capB(ab[0] + ab[1])
		case opIsub:
			assign(w, out, fmt.Sprintf("%s.Sub(%s)", a[0], a[1]))
			// The difference wraps when b can be larger than a. Only a
			// literal a gives a bound.
			if strings.HasPrefix(s.args[0], "#") && ab[1] <= ab[0] {
				bound[out] = ab[0]
			} else {
				bound[out] = huge
			}
		case opDiv255:
			v, b := reduce(a[0], ab[0])
			k255, _ := operand("#255", 'i')
			sum := fmt.Sprintf("%s.Add(%s)", v, k255)
			sum, _ = reduce(sum, b+255)
			assign(w, out, sum+".ShiftAllRight(8)")
			bound[out] = 0xff
		case opLoadf, opLoadi:
			usesPx = true
			consts["kff"] = "archsimd.BroadcastUint32x8(0xff)"
			for c, n := range s.outs {
				var e string
				switch c {
				case 0:
					e = "pxv.And(kff)"
				case 3:
					e = "pxv.ShiftAllRight(24)"
				default:
					e = fmt.Sprintf("pxv.ShiftAllRight(%d).And(kff)", 8*c)
				}
				if s.op == opLoadf {
					consts["kunit"] = "archsimd.BroadcastFloat32x8(fusedUnit)"
					e += ".AsInt32x8().ConvertToFloat32().Mul(kunit)"
				}
				assign(w, n, e)
				bound[n] = 0xff
			}
		case opLoadmask:
			usesMask = true
			assign(w, out, "vLoadBytes8(mask[i:])")
			bound[out] = 0xff
		case opSkipzero:
			fmt.Fprintf(w, "if %s.IsZero() {\ncontinue\n}\n", a[0])
		case opStoref:
			var parts []string
			for c, n := range s.args {
				e := fmt.Sprintf("vUnnorm8(%s)", n)
				if c > 0 {
					e += fmt.Sprintf(".ShiftAllLeft(%d)", 8*c)
				}
				parts = append(parts, e)
			}
			fmt.Fprintf(w, "vStorePixels8(px[i*4:], %s.Or(%s).Or(%s).Or(%s))\n", parts[0], parts[1], parts[2], parts[3])
		case opStorei:
			consts["kff"] = "archsimd.BroadcastUint32x8(0xff)"
			var parts []string
			for c, n := range s.args {
				e := n
				// The shift of a by 24 drops the high bits itself.
				if bound[n] > 0xff && c < 3 {
					e += ".And(kff)"
				}
				if c > 0 {
					e += fmt.Sprintf(".ShiftAllLeft(%d)", 8*c)
				}
				parts = append(parts, e)
			}
			fmt.Fprintf(w, "vStorePixels8(px[i*4:], %s.Or(%s).Or(%s).Or(%s))\n", parts[0], parts[1], parts[2], parts[3])
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// fused%sSIMD draws a row with the program Fused%s, 8 pixels\n", p.name, p.name)
	b.WriteString("// at a time, and the pixels that are left with the scalar code.\n")
	fmt.Fprintf(&b, "func fused%sSIMD(c *FusedCtx, px, mask []byte, x0, y0, n int) {\n", p.name)
	b.WriteString("px = px[:n*4]\n")
	if usesMask {
		b.WriteString("mask = mask[:n]\n")
	}
	for _, name := range []string{"k16", "kff", "kunit"} {
		if e, ok := consts[name]; ok {
			fmt.Fprintf(&b, "%s := %s\n", name, e)
		}
	}
	for _, name := range constOrder {
		fmt.Fprintf(&b, "%s := %s\n", name, consts[name])
	}
	b.Write(pre.Bytes())
	if usesSeedX {
		b.WriteString("iotaLo := archsimd.LoadFloat32x8Array(&[8]float32{0.5, 1.5, 2.5, 3.5, 4.5, 5.5, 6.5, 7.5})\n")
		if p.group > 8 {
			b.WriteString("iotaHi := archsimd.LoadFloat32x8Array(&[8]float32{8.5, 9.5, 10.5, 11.5, 12.5, 13.5, 14.5, 15.5})\n")
		}
	}
	b.WriteString("i := 0\nfor ; i+8 <= n; i += 8 {\n")
	if usesSeedX {
		if p.group > 8 {
			fmt.Fprintf(&b, "iot := iotaLo\nif i%%%d != 0 {\niot = iotaHi\n}\n", p.group)
		} else {
			b.WriteString("iot := iotaLo\n")
		}
	}
	if usesPx {
		b.WriteString("pxv := vLoadPixels8(px[i*4:])\n")
	}
	b.Write(body.Bytes())
	b.WriteString("}\n")
	fmt.Fprintf(&b, "fused%sScalar(c, px, mask, x0, y0, i, n)\n}\n\n", p.name)
	return b.String()
}

// programsFile gives fused_programs.go.
func programsFile() string {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package wide\n\n")
	b.WriteString("// FusedProgram names a fused program of D98. The zero value names no\n// program.\n")
	b.WriteString("type FusedProgram uint8\n\n")
	b.WriteString("// The fused programs.\nconst (\n")
	b.WriteString("// FusedNone names no program.\nFusedNone FusedProgram = iota\n")
	for _, p := range table {
		fmt.Fprintf(&b, "// Fused%s %s\nFused%s\n", p.name, p.doc, p.name)
	}
	b.WriteString(")\n\n")
	b.WriteString("// fusedRowScalar draws the pixels of a row with the scalar code of the\n// program prog.\n")
	b.WriteString("func fusedRowScalar(prog FusedProgram, c *FusedCtx, px, mask []byte, x, y, n int) {\nswitch prog {\n")
	for _, p := range table {
		fmt.Fprintf(&b, "case Fused%s:\nfused%sScalar(c, px, mask, x, y, 0, n)\n", p.name, p.name)
	}
	b.WriteString("}\n}\n\n")
	for _, p := range table {
		b.WriteString(scalarFunc(p))
	}
	return b.String()
}

// rowDoc is the doc comment of FusedRow.
const rowDoc = `// FusedRow draws n pixels of a row with the fused program prog. px holds the
// bytes of the pixels from the first one, and mask the bytes of the mask from
// the first pixel, for a program that reads a mask. x and y are the place of
// the first pixel, where the pipeline starts its groups of pixels. It gives
// the same bytes as the stages of the program.
`

// scalarFile gives fused_scalar.go.
func scalarFile() string {
	return header + tagScalar + "\n\npackage wide\n\n" + rowDoc +
		"func FusedRow(prog FusedProgram, c *FusedCtx, px, mask []byte, x, y, n int) {\n" +
		"fusedRowScalar(prog, c, px, mask, x, y, n)\n}\n"
}

// amd64File gives fused_simd_amd64.go.
func amd64File() string {
	var b bytes.Buffer
	b.WriteString(header + tagAMD64 + "\n\npackage wide\n\nimport \"simd/archsimd\"\n\n")
	b.WriteString(rowDoc)
	b.WriteString("//\n// It runs the SIMD code if useSIMD is true, and the scalar code otherwise.\n")
	b.WriteString("// The SIMD code clears the upper bits of the vector registers when it\n// ends, because the code after it runs plain float code.\n")
	b.WriteString("func FusedRow(prog FusedProgram, c *FusedCtx, px, mask []byte, x, y, n int) {\n")
	b.WriteString("if !useSIMD {\nfusedRowScalar(prog, c, px, mask, x, y, n)\nreturn\n}\nswitch prog {\n")
	for _, p := range table {
		fmt.Fprintf(&b, "case Fused%s:\nfused%sSIMD(c, px, mask, x, y, n)\n", p.name, p.name)
	}
	b.WriteString("}\narchsimd.ClearAVXUpperBits()\n}\n\n")
	for _, p := range table {
		b.WriteString(simdFunc(p))
	}
	return b.String()
}

func main() {
	dir := flag.String("dir", ".", "the folder of the package wide")
	out := flag.String("out", "", "the folder to write the files to (default: -dir)")
	flag.Parse()
	if *out == "" {
		*out = *dir
	}
	files := map[string]string{
		"fused_programs.go":   programsFile(),
		"fused_scalar.go":     scalarFile(),
		"fused_simd_amd64.go": amd64File(),
	}
	for name, src := range files {
		b, err := format.Source([]byte(src))
		if err != nil {
			log.Fatalf("%s: %v\n%s", name, err, src)
		}
		if err := os.WriteFile(filepath.Join(*out, name), b, 0o600); err != nil {
			log.Fatal(err)
		}
	}
}
