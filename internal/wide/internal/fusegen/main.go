// The ops of the language of the table.
const (
	opSeedx    = "seedx"
	opSeedy    = "seedy"
	opFparam   = "fparam"
	opIparam   = "iparam"
	opMadd     = "madd"
	opFmul     = "fmul"
	opFsub     = "fsub"
	opClamp01  = "clamp01"
	opTou16    = "tou16"
	opImul     = "imul"
	opIadd     = "iadd"
	opIsub     = "isub"
	opDiv255   = "div255"
	opLoadf    = "loadf"
	opLoadi    = "loadi"
	opLoadmask = "loadmask"
	opSkipzero = "skipzero"
	opStoref   = "storef"
	opStorei   = "storei"
)

// program is one fused program of the table.
type program struct {
	// name is the name of the constant of the program, after "Fused".
	name string
	// doc is the doc comment of the constant, after its name.
	doc string
	// group is the stage width of the pipeline that runs the stages: 8 for
	// highp and 16 for lowp. Only seedx reads it, because the x of a pixel
	// is the x of its group plus the place of the pixel in the group.
	group int
	// body holds the statements.
	body string
}

// sourceOverI is the stage source_over of lowp on the channels r, g, b and
// a: the destination scaled by 255 - a, added to the source. Then it stores
// the pixel. source_over_rgba is the same arithmetic.
func sourceOverI(r, g, b, a string) string {
	return strings.NewReplacer("R", r, "G", g, "B", b, "A", a).Replace(`
dr dg db da = loadi
ia = isub #255 A
dr = imul dr ia
dr = div255 dr
R = iadd R dr
dg = imul dg ia
dg = div255 dg
G = iadd G dg
db = imul db ia
db = div255 db
B = iadd B db
da = imul da ia
da = div255 da
A = iadd A da
storei R G B A
`)
}

