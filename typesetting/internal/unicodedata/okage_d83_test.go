// okage: the tests of D83.

var generateSegment = flag.Bool("unicodedata.generate", false, "write okage_segment_table.go from the tables of each property")

// TestSegmentProperties makes sure that LookupSegmentProperties gives the
// result of the lookup of each property for each rune, and for runes
// outside the range of Unicode.
func TestSegmentProperties(t *testing.T) {
	check := func(r rune) {
		got := *LookupSegmentProperties(r)
		want := SegmentProperties{
			LineBreak:            LookupLineBreak(r),
			GraphemeBreak:        LookupGraphemeBreak(r),
			WordBreak:            LookupWordBreak(r),
			GeneralCategory:      GeneralCategory(gcLookup(r)),
			IndicConjunctBreak:   LookupIndicConjunctBreak(r),
			ExtendedPictographic: IsExtendedPictographic(r),
		}
		if got != want {
			t.Fatalf("LookupSegmentProperties(%U) = %+v, want %+v", r, got, want)
		}
	}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		check(r)
	}
	for _, r := range []rune{-1, -0x100, unicode.MaxRune + 1, 0x7FFFFFFF, -0x80000000} {
		check(r)
	}
}

// TestGenerateSegmentTable writes okage_segment_table.go with the flag
// -unicodedata.generate. Without the flag, it makes sure that the file
// holds what the generator writes.
func TestGenerateSegmentTable(t *testing.T) {
	const name = "okage_segment_table.go"
	src := generateSegmentTable()
	if *generateSegment {
		if err := os.WriteFile(name, src, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	old, err := os.ReadFile(name)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(old, src) {
		t.Fatalf("%s is out of date: run go test -run TestGenerateSegmentTable -unicodedata.generate", name)
	}
}

// generateSegmentTable returns the source of okage_segment_table.go. Each
// block of 256 runes maps to one of the distinct blocks of segmentIndex,
// and each rune of a block holds the index of its properties in
// segmentRaw. The value 0, which the lookups give for a rune outside the
// range of Unicode, is segmentRaw[0].
func generateSegmentTable() []byte {
	const blockSize = 1 << segmentBlockBits
	raws := make([]uint32, unicode.MaxRune+1)
	values := []uint32{0}
	for r := range raws {
		raws[r] = packSegment(rune(r))
		values = append(values, raws[r])
	}
	slices.Sort(values)
	values = slices.Compact(values)
	index := map[uint32]uint8{}
	for i, v := range values {
		if i > 0xFF {
			panic("more than 256 sets of properties")
		}
		index[v] = uint8(i)
	}
	var (
		blocks   []uint8
		distinct [][]uint8
		seen     = map[string]int{}
	)
	for b := 0; b < len(raws)/blockSize; b++ {
		block := make([]uint8, blockSize)
		for i := range block {
			block[i] = index[raws[b*blockSize+i]]
		}
		n, ok := seen[string(block)]
		if !ok {
			n = len(distinct)
			if n > 0xFF {
				panic("more than 256 distinct blocks")
			}
			seen[string(block)] = n
			distinct = append(distinct, block)
		}
		blocks = append(blocks, uint8(n))
	}

	var buf bytes.Buffer
	buf.WriteString("// SPDX-License-Identifier: Unlicense OR BSD-3-Clause\n\npackage unicodedata\n\n")
	buf.WriteString("// Code generated by TestGenerateSegmentTable in okage_d83_test.go. DO NOT EDIT.\n\n")
	buf.WriteString("// okage: D83. The table of LookupSegmentProperties.\n\n")
	fmt.Fprintf(&buf, "var segmentRaw = [%d]uint32{\n", len(values))
	writeValues(&buf, values)
	fmt.Fprintf(&buf, "}\n\nvar segmentBlocks = [%d]uint8{\n", len(blocks))
	writeValues(&buf, blocks)
	fmt.Fprintf(&buf, "}\n\nvar segmentIndex = [%d]uint8{\n", len(distinct)*blockSize)
	writeValues(&buf, slices.Concat(distinct...))
	buf.WriteString("}\n")
	return buf.Bytes()
}

// writeValues writes the values in lines of 20.
func writeValues[T uint8 | uint32](buf *bytes.Buffer, values []T) {
	for i, v := range values {
		switch {
		case i%20 == 0:
			buf.WriteByte('\t')
		default:
			buf.WriteByte(' ')
		}
		fmt.Fprintf(buf, "%d,", v)
		if i%20 == 19 || i == len(values)-1 {
			buf.WriteByte('\n')
		}
	}
}
