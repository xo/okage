// Command usegen writes ot_shape_use_table.go, the table of the categories
// of the USE shaper of harfbuzz. It reads the files of the Unicode
// Character Database in upstream/unicode-ucd with the package usetable, the
// port of gen-use-table.py of HarfBuzz 15.2.0, and packs the table as the
// generator of go-text does (D101).
//
// Run "go generate ./typesetting/harfbuzz" in the repository. The command
// looks for upstream/unicode-ucd in the working folder and in each folder
// above it. The flag -ucd gives another folder.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strings"

	"github.com/xo/okage/typesetting/harfbuzz/internal/packtab"
	"github.com/xo/okage/typesetting/harfbuzz/internal/usetable"
)

func main() {
	ucd := flag.String("ucd", "", "the folder of the data files, by default upstream/unicode-ucd")
	out := flag.String("o", "ot_shape_use_table.go", "the output file")
	flag.Parse()

	dir := *ucd
	if dir == "" {
		var err error
		dir, err = usetable.FindDir()
		if err != nil {
			log.Fatal(err)
		}
	}
	src, err := generate(dir)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

var versionRe = regexp.MustCompile(`-(\d+\.\d+\.\d+)\.txt`)

func generate(dir string) ([]byte, error) {
	t, err := usetable.Load(dir)
	if err != nil {
		return nil, err
	}

	maxRune := rune(0)
	for u := range t.Category {
		maxRune = max(maxRune, u)
	}
	table := make([]int, maxRune+1)
	for u, c := range t.Category {
		v, ok := usetable.Categories[c]
		if !ok {
			return nil, fmt.Errorf("generating the USE table: no value for the category %s", c)
		}
		table[u] = int(v)
	}

	version := "unknown"
	if m := versionRe.FindStringSubmatch(t.Headers[0]); m != nil {
		version = m[1]
	}

	var w bytes.Buffer
	fmt.Fprintln(&w, "// SPDX-License-Identifier: Unlicense OR BSD-3-Clause")
	fmt.Fprintln(&w)
	fmt.Fprintln(&w, "package harfbuzz")
	fmt.Fprintln(&w)
	fmt.Fprintln(&w, "// Code generated by typesetting/harfbuzz/internal/usegen. DO NOT EDIT.")
	fmt.Fprintln(&w, "// Unicode version", version)
	fmt.Fprintln(&w, "//")
	fmt.Fprintln(&w, "// The input files have these headers:")
	fmt.Fprintln(&w, "//")
	for _, h := range t.Headers {
		fmt.Fprintln(&w, strings.TrimSpace("// "+h))
	}
	fmt.Fprintln(&w, "// UnicodeData.txt does not have a header.")
	fmt.Fprintln(&w)
	fmt.Fprintln(&w, packtab.PackTable(table, int(usetable.Categories["O"]), 5).Code("use"))

	src, err := format.Source(w.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the USE table: %w", err)
	}
	return src, nil
}
