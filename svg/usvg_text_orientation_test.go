package svg

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
	"testing"
)

// This file holds the generator of usvg_text_orientation.go and its test.
//
// The crate unicode-vo, which usvg calls, is based on
// https://www.unicode.org/Public/vertical/revision-17/VerticalOrientation-17.txt.
// go-text has the property only in an internal package, so the table is made
// from that file. To make the table again, download the file and run:
//
//	go test ./svg/ -run TestOrientationTable -svg.vo=VerticalOrientation-17.txt

// voFile is the flag -svg.vo, the path of VerticalOrientation-17.txt.
var voFile = flag.String("svg.vo", "", "write usvg_text_orientation.go from this VerticalOrientation-17.txt")

// generateOrientationTable returns the source of usvg_text_orientation.go,
// made from the text of VerticalOrientation-17.txt.
func generateOrientationTable(data []byte) ([]byte, error) {
	type rng struct{ lo, hi uint32 }
	var ranges []rng
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		fields := strings.Split(line, ";")
		if len(fields) != 2 || strings.TrimSpace(fields[1]) != "U" {
			continue
		}
		cps := strings.TrimSpace(fields[0])
		loS, hiS, found := strings.Cut(cps, "..")
		if !found {
			hiS = loS
		}
		lo, err := strconv.ParseUint(loS, 16, 32)
		if err != nil {
			return nil, err
		}
		hi, err := strconv.ParseUint(hiS, 16, 32)
		if err != nil {
			return nil, err
		}
		if n := len(ranges); n > 0 && ranges[n-1].hi+1 == uint32(lo) {
			ranges[n-1].hi = uint32(hi)
			continue
		}
		ranges = append(ranges, rng{uint32(lo), uint32(hi)})
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(`// Code generated by TestOrientationTable in usvg_text_orientation_test.go from
// VerticalOrientation-17.txt; DO NOT EDIT.

package svg

// uprightRanges holds the ranges of the code points whose Vertical_Orientation
// is U (upright), first and last, in order. The other code points are R, Tu or
// Tr.
var uprightRanges = [...][2]rune{
`)
	for _, r := range ranges {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", r.lo, r.hi)
	}
	b.WriteString(`}

// charOrientationUpright is unicode_vo::char_orientation(c) ==
// Orientation::Upright, which usvg src/text/layout.rs calls.
func charOrientationUpright(c rune) bool {
	lo, hi := 0, len(uprightRanges)
	for lo < hi {
		m := int(uint(lo+hi) >> 1)
		switch r := uprightRanges[m]; {
		case c < r[0]:
			hi = m
		case c > r[1]:
			lo = m + 1
		default:
			return true
		}
	}
	return false
}
`)
	return format.Source(b.Bytes())
}

// TestOrientationTable checks charOrientationUpright, and writes
// usvg_text_orientation.go again with the flag -svg.vo.
func TestOrientationTable(t *testing.T) {
	if *voFile != "" {
		data, err := os.ReadFile(*voFile)
		if err != nil {
			t.Fatal(err)
		}
		src, err := generateOrientationTable(data)
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile("usvg_text_orientation.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	// The examples of the documentation of unicode-vo, and a few more.
	for _, c := range []struct {
		r    rune
		want bool
	}{
		{'A', false},
		{'本', true},
		{0x00A7, true},
		{0x00A8, false},
		{0x1100, true},
		{0x3001, false}, // Tu
		{0x10FFFD, true},
		{0x10FFFE, false},
	} {
		if got := charOrientationUpright(c.r); got != c.want {
			t.Errorf("charOrientationUpright(%U) = %v, want %v", c.r, got, c.want)
		}
	}
}
